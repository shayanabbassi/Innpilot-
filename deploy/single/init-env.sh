#!/bin/sh
# Writes the settings files for the single-server stack (P7-1, P7-7) in the current directory: app.env, release.env,
# backup.env, postgres.env, monitoring.env, and backup-private.env (the backup private key: copy it somewhere safe
# off this machine, then delete it here; docs/staging-runbook.md step 6).
#   cd /opt/innpilot && sh init-env.sh
# Asks for the public address and the two Cloudflare R2 buckets with their tokens; every other secret is generated
# here with openssl. Safe to run again: files that exist are kept. Each answer can also come from the environment
# under the same name (SITE_ADDRESS, R2_ENDPOINT, FILES_BUCKET, FILES_KEY_ID, FILES_SECRET, BACKUP_BUCKET_NAME,
# BACKUP_KEY_ID, BACKUP_SECRET), which the tests use.
set -eu
umask 077

secret() { openssl rand -base64 "${1:-32}" | tr '+/' '-_' | tr -d '=\n'; }
ask() {
  # $1 variable, $2 question, $3 "hidden" for secrets
  eval "current=\${$1:-}"
  if [ -z "$current" ]; then
    printf '%s: ' "$2" >&2
    if [ "${3:-}" = hidden ]; then
      stty -echo 2>/dev/null || true
      read -r current
      stty echo 2>/dev/null || true
      echo >&2
    else
      read -r current
    fi
  fi
  [ -n "$current" ] || { echo "$2 is required." >&2; exit 1; }
  eval "$1=\$current"
}
write() {
  if [ -e "$1" ]; then
    echo "Kept $1 (already exists)."
    cat >/dev/null
  else
    { echo "# Single-server stack settings. Generated by init-env.sh; never copy into git or chat."; cat; } >"$1"
    chmod 600 "$1"
    echo "Wrote $1"
  fi
}
value() { sed -n "s/^$2=//p" "$1" 2>/dev/null | head -n 1; }

command -v openssl >/dev/null || { echo "openssl is needed (apt install openssl)." >&2; exit 1; }

ask SITE_ADDRESS 'Public address, without https:// (e.g. innpilot-staging.duckdns.org)'
ask R2_ENDPOINT 'R2 endpoint (https://<account id>.r2.cloudflarestorage.com)'
ask FILES_BUCKET 'R2 bucket for application files'
ask FILES_KEY_ID 'Access key ID of the files bucket token'
ask FILES_SECRET 'Secret access key of the files bucket token' hidden
ask BACKUP_BUCKET_NAME 'R2 bucket for backups'
ask BACKUP_KEY_ID 'Access key ID of the backup bucket token'
ask BACKUP_SECRET 'Secret access key of the backup bucket token' hidden

case "$R2_ENDPOINT" in https://*) ;; *) echo 'The R2 endpoint must start with https://' >&2; exit 1 ;; esac
[ "$FILES_BUCKET" != "$BACKUP_BUCKET_NAME" ] || { echo 'Use two different buckets (P7-3).' >&2; exit 1; }

# Shared values: reuse what an earlier run wrote, so the files always agree.
POSTGRES_PASSWORD=$(value postgres.env POSTGRES_PASSWORD)
[ -n "$POSTGRES_PASSWORD" ] || POSTGRES_PASSWORD=$(secret 24)
APP_DB_PASSWORD=$(value release.env APP_DB_PASSWORD)
[ -n "$APP_DB_PASSWORD" ] || APP_DB_PASSWORD=$(secret 24)

write postgres.env <<EOF
POSTGRES_DB=innpilot
POSTGRES_USER=postgres
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
EOF

write release.env <<EOF
DATABASE_ADMIN_URL=postgres://postgres:$POSTGRES_PASSWORD@postgres:5432/innpilot
APP_DB_PASSWORD=$APP_DB_PASSWORD
EOF

write app.env <<EOF
DATABASE_URL=postgres://innpilot_app:$APP_DB_PASSWORD@postgres:5432/innpilot
WEB_ORIGINS=https://$SITE_ADDRESS
COOKIE_SECURE=true
MFA_ENCRYPTION_KEY=$(secret 32)
PII_ENCRYPTION_KEY=$(secret 32)
SESSION_IDLE_MINUTES=30
SESSION_ABSOLUTE_HOURS=12
LOG_LEVEL=info
JOBS_POLL_SECONDS=5
STORAGE_ENDPOINT=$R2_ENDPOINT
STORAGE_REGION=auto
STORAGE_BUCKET=$FILES_BUCKET
STORAGE_ACCESS_KEY_ID=$FILES_KEY_ID
STORAGE_SECRET_ACCESS_KEY=$FILES_SECRET
EOF

if [ ! -e backup.env ]; then
  # RSA-4096 pair in the format "dist/ops/cli.js keygen" prints: base64 DER, SPKI public and PKCS#8 private.
  work=$(mktemp -d)
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:4096 -out "$work/private.pem" 2>/dev/null
  # Explicitly PKCS#8: some OpenSSL versions write the older PKCS#1 form for DER, which the restore cannot read.
  openssl pkcs8 -topk8 -nocrypt -in "$work/private.pem" -outform DER -out "$work/private.der"
  openssl pkey -in "$work/private.pem" -pubout -outform DER -out "$work/public.der"
  BACKUP_PUBLIC_KEY=$(openssl base64 -A -in "$work/public.der")
  BACKUP_PRIVATE_KEY=$(openssl base64 -A -in "$work/private.der")
  rm -rf "$work"
  write backup.env <<EOF
BACKUP_STORAGE_ENDPOINT=$R2_ENDPOINT
BACKUP_STORAGE_REGION=auto
BACKUP_BUCKET=$BACKUP_BUCKET_NAME
BACKUP_ACCESS_KEY_ID=$BACKUP_KEY_ID
BACKUP_SECRET_ACCESS_KEY=$BACKUP_SECRET
BACKUP_PUBLIC_KEY=$BACKUP_PUBLIC_KEY
BACKUP_AT_UTC=21:00
EOF
  write backup-private.env <<EOF
BACKUP_PRIVATE_KEY=$BACKUP_PRIVATE_KEY
EOF
  echo
  echo "IMPORTANT: backup-private.env holds the only key that can read the backups. Copy it to safe keeping off"
  echo "this machine (a password manager), then delete it here: rm backup-private.env"
else
  echo "Kept backup.env (already exists)."
fi

write monitoring.env <<EOF
GF_SECURITY_ADMIN_PASSWORD=$(secret 18)
EOF
