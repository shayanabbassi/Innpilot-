#!/usr/bin/env node
/**
 * Writes the local production-like stack's settings (deploy/local/*.env) with fresh random secrets. Safe to run
 * again: files that already exist are kept, and only missing ones are added (reusing the values they share).
 * These are local test values only: never reuse them anywhere else.
 *
 * Home staging (slice 7.1, docs/home-staging-runbook.md) uses the same settings in another folder, for its public
 * address and buckets:
 *   node deploy/local/init.mjs --dir deploy/home --origin https://<pc>.<tailnet>.ts.net --buckets innpilot-staging
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const here = resolve(arg('dir', dirname(fileURLToPath(import.meta.url))));
const origin = arg('origin', 'https://localhost:8443');
const buckets = arg('buckets', 'innpilot-local');
if (!/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(origin)) {
  throw new Error(`--origin must be https://host, not ${origin}`);
}
mkdirSync(here, { recursive: true });
const secret = (n = 24) => randomBytes(n).toString('base64url');
const read = (name) =>
  existsSync(join(here, name))
    ? Object.fromEntries(
        readFileSync(join(here, name), 'utf8')
          .split('\n')
          .filter((l) => l.includes('=') && !l.startsWith('#'))
          .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
      )
    : null;

const pg = read('postgres.env');
const st = read('storage.env');
const rel = read('release.env');
const postgresPassword = pg?.POSTGRES_PASSWORD ?? secret();
const appPassword = rel?.APP_DB_PASSWORD ?? secret();
const storageKey = st?.ROOT_ACCESS_KEY_ID ?? `local${randomBytes(6).toString('hex')}`;
const storageSecret = st?.ROOT_SECRET_ACCESS_KEY ?? secret();

/** A backup key pair in the format dist/ops/cli.js keygen prints (base64 DER). */
function backupKeys() {
  const { publicKey, privateKey } = generateKeyPairSync('rsa', { modulusLength: 4096 });
  return {
    publicKey: publicKey.export({ type: 'spki', format: 'der' }).toString('base64'),
    privateKey: privateKey.export({ type: 'pkcs8', format: 'der' }).toString('base64'),
  };
}

const files = {
  'postgres.env': () => ({
    POSTGRES_DB: 'innpilot',
    POSTGRES_USER: 'postgres',
    POSTGRES_PASSWORD: postgresPassword,
  }),
  'storage.env': () => ({ ROOT_ACCESS_KEY_ID: storageKey, ROOT_SECRET_ACCESS_KEY: storageSecret }),
  'release.env': () => ({
    DATABASE_ADMIN_URL: `postgres://postgres:${postgresPassword}@postgres:5432/innpilot`,
    APP_DB_PASSWORD: appPassword,
  }),
  'app.env': () => ({
    DATABASE_URL: `postgres://innpilot_app:${appPassword}@postgres:5432/innpilot`,
    WEB_ORIGINS: origin,
    COOKIE_SECURE: 'true',
    MFA_ENCRYPTION_KEY: secret(32),
    PII_ENCRYPTION_KEY: secret(32),
    LOG_LEVEL: 'info',
    JOBS_POLL_SECONDS: '5',
    STORAGE_ENDPOINT: 'http://storage:7070',
    STORAGE_REGION: 'us-east-1',
    STORAGE_BUCKET: buckets,
    STORAGE_ACCESS_KEY_ID: storageKey,
    STORAGE_SECRET_ACCESS_KEY: storageSecret,
  }),
  'smoke.env': () => ({ SMOKE_EMAIL: 'smoke-owner@local.test', SMOKE_PASSWORD: secret(18) }),
  'monitoring.env': () => ({ GF_SECURITY_ADMIN_PASSWORD: secret(18) }),
};

// The backup pair is made together: the public half for the backup job, the private half kept apart (as the owner
// would keep it offline) and given only to the restore drill.
const needKeys = !existsSync(join(here, 'backup.env')) || !existsSync(join(here, 'backup-private.env'));
if (needKeys) {
  const keys = backupKeys();
  files['backup.env'] = () => ({
    // Locally the same storage container, another bucket; in production a separate account (runbook).
    BACKUP_STORAGE_ENDPOINT: 'http://storage:7070',
    BACKUP_STORAGE_REGION: 'us-east-1',
    BACKUP_BUCKET: `${buckets}-backups`,
    BACKUP_ACCESS_KEY_ID: storageKey,
    BACKUP_SECRET_ACCESS_KEY: storageSecret,
    BACKUP_PUBLIC_KEY: keys.publicKey,
    BACKUP_CREATE_BUCKET: 'true',
  });
  files['backup-private.env'] = () => ({ BACKUP_PRIVATE_KEY: keys.privateKey });
}

let written = 0;
for (const [name, values] of Object.entries(files)) {
  if (existsSync(join(here, name)) && !(needKeys && name.startsWith('backup'))) continue;
  const body = Object.entries(values())
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');
  writeFileSync(join(here, name), `# Local production-like stack only. Generated by init.mjs.\n${body}\n`, {
    mode: 0o600,
  });
  written++;
}
console.log(
  written
    ? `Wrote ${written} file(s) in ${relative(process.cwd(), here) || '.'} with random secrets.`
    : `${relative(process.cwd(), here) || '.'} is complete.`,
);
