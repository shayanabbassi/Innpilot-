#!/usr/bin/env node
/**
 * Writes the local production-like stack's settings (deploy/local/*.env) with fresh random secrets. Run once; it
 * never overwrites existing files. These are local test values only: never reuse them anywhere else.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const secret = (n = 24) => randomBytes(n).toString('base64url');

const postgresPassword = secret();
const appPassword = secret();
const storageKey = `local${randomBytes(6).toString('hex')}`;
const storageSecret = secret();

const files = {
  'postgres.env': { POSTGRES_DB: 'innpilot', POSTGRES_USER: 'postgres', POSTGRES_PASSWORD: postgresPassword },
  'storage.env': { ROOT_ACCESS_KEY_ID: storageKey, ROOT_SECRET_ACCESS_KEY: storageSecret },
  'release.env': {
    DATABASE_ADMIN_URL: `postgres://postgres:${postgresPassword}@postgres:5432/innpilot`,
    APP_DB_PASSWORD: appPassword,
  },
  'app.env': {
    DATABASE_URL: `postgres://innpilot_app:${appPassword}@postgres:5432/innpilot`,
    WEB_ORIGINS: 'https://localhost:8443',
    COOKIE_SECURE: 'true',
    MFA_ENCRYPTION_KEY: secret(32),
    PII_ENCRYPTION_KEY: secret(32),
    LOG_LEVEL: 'info',
    JOBS_POLL_SECONDS: '5',
    STORAGE_ENDPOINT: 'http://storage:7070',
    STORAGE_REGION: 'us-east-1',
    STORAGE_BUCKET: 'innpilot-local',
    STORAGE_ACCESS_KEY_ID: storageKey,
    STORAGE_SECRET_ACCESS_KEY: storageSecret,
  },
  'smoke.env': { SMOKE_EMAIL: 'smoke-owner@local.test', SMOKE_PASSWORD: secret(18) },
};

if (Object.keys(files).some((f) => existsSync(join(here, f)))) {
  console.log('deploy/local already has settings; nothing changed.');
  process.exit(0);
}
for (const [name, values] of Object.entries(files)) {
  const body = Object.entries(values)
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');
  writeFileSync(join(here, name), `# Local production-like stack only. Generated by init.mjs.\n${body}\n`, {
    mode: 0o600,
  });
}
console.log('Wrote deploy/local/*.env with random local secrets.');
